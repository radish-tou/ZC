void delay_us(uint32_t nus)
{
	uint32_t ticks;
	uint32_t told, tnow, tcnt = 0;
	uint32_t reload = SysTick->LOAD; // LOAD???
	ticks = nus * fac_us;			 // ??????????
	told = SysTick->VAL;			 // ??????????????
	while (1)
	{
		tnow = SysTick->VAL;
		if (tnow != told)
		{
			if (tnow < told)
				tcnt += told - tnow; // ??????????SYSTICK??????????????????????.
			else
				tcnt += reload - tnow + told;
			told = tnow;
			if (tcnt >= ticks)
				break; // ?????/????????????,?????.
		}
	};
}

// ???nms
// nms:??????ms??
void delay_ms(uint16_t nms)
{
	uint32_t i;
	for (i = 0; i < nms; i++)
		delay_us(1000);
}
